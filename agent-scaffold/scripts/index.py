#!/usr/bin/env python3
"""Regenerate the generated indexes. Never hand-edit an INDEX.md.

  index.py            # rebuild agents/registers/{decisions,lessons,examples}/INDEX.md
  index.py --check    # exit 1 if any index is stale or any register entry is malformed

In-force only: entries with status superseded/dropped/retired are left out of the index (they
cost context and give nothing). Newest first, one line per entry. Also validates: frontmatter
present, date matches filename, no duplicate ids.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402

OUT_OF_FORCE = {"superseded", "dropped", "retired", "deleted"}
DATE_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})-")

HEADER = ("<!-- generated by agents/scripts/index.py — do not edit; in-force entries only, newest first -->\n")


def entries(folder: Path, exts=(".md",)) -> list[tuple[Path, dict, list[str]]]:
    out = []
    if not folder.exists():
        return out
    for p in sorted(folder.iterdir()):
        if p.name == "INDEX.md" or p.name.startswith(".") or p.suffix not in exts:
            continue
        problems = []
        fm, _ = C.read_entry(p)
        if not fm:
            problems.append("no frontmatter")
        m = DATE_RE.match(p.stem)
        if not m:
            problems.append("filename does not start with YYYY-MM-DD-")
        elif fm.get("date") and str(fm["date"]) != m.group(1):
            problems.append(f"date {fm['date']} != filename {m.group(1)}")
        out.append((p, fm, problems))
    return out


def render_md_index(title: str, folder: Path, cols: list[str]) -> tuple[str, list[str]]:
    rows, problems = [], []
    seen = set()
    for p, fm, probs in entries(folder):
        for pr in probs:
            problems.append(f"{p.name}: {pr}")
        if p.stem in seen:
            problems.append(f"{p.name}: duplicate id")
        seen.add(p.stem)
        if str(fm.get("status", "")).lower() in OUT_OF_FORCE:
            continue
        vals = []
        for c in cols:
            v = fm.get(c, "")
            if isinstance(v, list):
                v = ", ".join(str(x) for x in v)
            vals.append(str(v).replace("|", "/"))
        rows.append((str(fm.get("date", "")), f"| {' | '.join(vals)} | [{p.stem}]({p.name}) |"))
    rows.sort(key=lambda r: r[0], reverse=True)
    text = HEADER + f"# {title} — index ({len(rows)} in force)\n\n"
    text += "| " + " | ".join(cols) + " | file |\n|" + "---|" * (len(cols) + 1) + "\n"
    text += "\n".join(r[1] for r in rows) + ("\n" if rows else "_none yet_\n")
    return text, problems


def render_examples_index(folder: Path) -> tuple[str, list[str]]:
    rows, problems = [], []
    if folder.exists():
        for side in sorted(folder.glob("*.json")):
            try:
                d = json.loads(side.read_text(encoding="utf-8"))
            except json.JSONDecodeError as e:
                problems.append(f"{side.name}: bad JSON ({e})")
                continue
            f = folder / str(d.get("file", ""))
            if not f.is_file():
                problems.append(f"{side.name}: file {d.get('file')} missing")
            if str(d.get("status", "")).lower() in OUT_OF_FORCE:
                continue
            settings = "; ".join(f"{k}={v}" for k, v in (d.get("settings") or {}).items())
            rows.append((str(d.get("created", "")),
                         f"| {d.get('created', '')} | {d.get('title', side.stem)} | {settings} | [{d.get('file', '')}]({d.get('file', '')}) |"))
        for f in folder.iterdir():
            if f.is_file() and f.suffix not in (".json", ".md") and not f.name.startswith("."):
                if not (folder / (f.stem + ".json")).exists():
                    problems.append(f"{f.name}: example without sidecar")
    rows.sort(key=lambda r: r[0], reverse=True)
    text = HEADER + f"# Examples — index ({len(rows)} current)\n\n| created | title | settings | file |\n|---|---|---|---|\n"
    text += "\n".join(r[1] for r in rows) + ("\n" if rows else "_none yet_\n")
    return text, problems


def build(L: C.Layout) -> tuple[dict[Path, str], list[str]]:
    outputs, problems = {}, []
    t, p = render_md_index("Decisions", L.decisions, ["date", "status", "title"]); outputs[L.decisions / "INDEX.md"] = t; problems += p
    t, p = render_md_index("Lessons", L.lessons, ["date", "rung", "helpful", "harmful", "title"]); outputs[L.lessons / "INDEX.md"] = t; problems += p
    t, p = render_examples_index(L.examples); outputs[L.examples / "INDEX.md"] = t; problems += p
    return outputs, problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root")
    a = ap.parse_args()
    L = C.Layout(C.find_root(a.root))
    outputs, problems = build(L)
    stale = [p for p, t in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
    for pr in problems:
        print("problem:", pr)
    if a.check:
        for p in stale:
            print("stale:", L.rel(p))
        return 1 if (stale or problems) else 0
    for p, t in outputs.items():
        if p.parent.exists():
            C.atomic_write(p, t)
    print(f"indexes written: {len([p for p in outputs if p.parent.exists()])}; problems: {len(problems)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
